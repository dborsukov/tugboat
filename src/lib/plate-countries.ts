export interface PlateCountry {
  code: string;
  name: string;
  englishName: string;
}

function displayNames(locale: string, fallbackToCode = true) {
  try {
    return new Intl.DisplayNames([locale], {
      type: "region",
      fallback: fallbackToCode ? "code" : "none",
    });
  } catch {
    return null;
  }
}

const ukNames = displayNames("uk");
const enNames = displayNames("en");

export const PLATE_COUNTRIES: PlateCountry[] = PLATE_COUNTRY_CODES.map(
  (code) => ({
    code,
    name: ukNames?.of(code) ?? code,
    englishName: enNames?.of(code) ?? code,
  }),
).sort((a, b) => a.name.localeCompare(b.name, "uk"));

const BY_CODE = new Map(
  PLATE_COUNTRIES.map((country) => [country.code, country]),
);

export function plateCountry(
  code: string | null | undefined,
): PlateCountry | null {
  if (!code) return null;
  return BY_CODE.get(code.toUpperCase()) ?? null;
}

export function plateCountryName(code: string | null | undefined): string {
  return plateCountry(code)?.name ?? code?.toUpperCase() ?? "";
}

export function filterPlateCountries(query: string): PlateCountry[] {
  const needle = query.trim().toLocaleLowerCase("uk");
  if (!needle) return PLATE_COUNTRIES;
  return PLATE_COUNTRIES.filter((country) => {
    const name = country.name.toLocaleLowerCase("uk");
    return (
      name.includes(needle) ||
      country.code.toLocaleLowerCase("uk").includes(needle) ||
      country.englishName.toLocaleLowerCase("en").includes(needle)
    );
  });
}
